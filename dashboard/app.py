"""Streamlit entry point.

Run locally with ``streamlit run dashboard/app.py`` (or ``python run.py dashboard``).
On Streamlit Community Cloud the main file path is ``dashboard/app.py`` and the
requirements are the repository's ``requirements.txt``.
"""

from __future__ import annotations

import sys
from pathlib import Path

import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from dashboard.theme import CUSTOM_CSS, fmt_compact, fmt_money, load_feed  # noqa: E402
from dashboard.views import about, anomalies, explorer, forecast, overview, products, seasonality  # noqa: E402

TABS = (
    ("Overview", overview.render),
    ("Seasonality", seasonality.render),
    ("Products", products.render),
    ("Forecast", forecast.render),
    ("Anomalies", anomalies.render),
    ("Explore", explorer.render),
    ("About", about.render),
)


def main() -> None:
    st.set_page_config(
        page_title="Superstore sales time series",
        page_icon="📈",
        layout="wide",
        initial_sidebar_state="expanded",
    )
    st.markdown(CUSTOM_CSS, unsafe_allow_html=True)

    try:
        feed = load_feed()
    except FileNotFoundError as error:
        st.error(str(error))
        st.code("python run.py all", language="bash")
        st.stop()

    sales = feed["kpis"]["sales"]
    forecast_payload = feed["kpis"]["forecast"]

    st.title("Superstore product sales, 2014-2017")
    st.caption(
        "A time-series analysis of 9,994 order lines: trend, seasonality, product concentration, "
        "anomalies and a 13-week revenue forecast."
    )

    with st.sidebar:
        st.markdown("### At a glance")
        st.metric("Revenue", fmt_compact(sales["total_sales"]))
        st.metric("Orders", f"{sales['orders']:,}")
        st.metric("Products", f"{sales['products']:,}")
        st.metric("Forecast RMSE", fmt_money(forecast_payload["test"]["rmse"]))
        st.caption(
            f"{feed['dimensions']['date_min']} to {feed['dimensions']['date_max']}"
        )
        st.divider()
        st.markdown("### Pages")
        st.markdown(
            "- **Overview** level, growth and mix\n"
            "- **Seasonality** trend and calendar effects\n"
            "- **Products** Pareto and behavioural segments\n"
            "- **Forecast** 13-week model and its errors\n"
            "- **Anomalies** weeks that broke the pattern\n"
            "- **Explore** filter and download\n"
            "- **About** method, limits, links"
        )
        st.divider()
        st.caption(
            "Every number is regenerated by `python run.py all` from a SHA-256 pinned dataset. "
            "The raw data is not committed; the dashboard feed is."
        )

    tabs = st.tabs([label for label, _ in TABS])
    for tab, (_, render) in zip(tabs, TABS, strict=True):
        with tab:
            render(feed)

    st.divider()
    st.caption(
        "Built by Manish · pandas, scikit-learn, matplotlib, Streamlit · "
        "source: Tableau/Kaggle Sample - Superstore"
    )


main()
