"""About tab: method, provenance and limits in one place."""

from __future__ import annotations

import streamlit as st
from dashboard.theme import fmt_money, fmt_pct

REPO_URL = "https://github.com/Manish27-tech/superstore-sales-timeseries"


def render(feed: dict) -> None:
    sales = feed["kpis"]["sales"]
    forecast = feed["kpis"]["forecast"]
    dimensions = feed["dimensions"]

    st.markdown("### About this analysis")
    st.markdown(
        "A complete time-series project on the Tableau/Kaggle *Sample - Superstore* extract: "
        "verification, cleaning, aggregation, decomposition, product segmentation, anomaly detection "
        "and a 13-week revenue forecast, with every figure regenerated by one command."
    )

    left, right = st.columns(2)
    with left:
        st.markdown("##### Dataset")
        st.markdown(
            f"- **{sales['rows']:,}** order lines, **{sales['orders']:,}** orders, "
            f"**{sales['customers']:,}** customers, **{sales['products']:,}** products\n"
            f"- **{dimensions['date_min']}** to **{dimensions['date_max']}**\n"
            f"- {len(dimensions['categories'])} categories, {len(dimensions['sub_categories'])} sub-categories, "
            f"{len(dimensions['regions'])} regions\n"
            f"- Total sales {fmt_money(sales['total_sales'])} at a {fmt_pct(sales['margin'])} margin\n"
            f"- SHA-256 pinned, with row, order and total checks that fail the build on drift"
        )
        st.markdown("##### Method")
        st.markdown(
            "- **Aggregation:** Monday-starting weeks, calendar months, zero-filled days.\n"
            "- **Decomposition:** multiplicative, centred 12-month moving average trend, "
            "month-average seasonal factors.\n"
            "- **Segments:** ABC on cumulative revenue plus k-means (k=4) on log revenue, growth, "
            "volatility and margin.\n"
            "- **Anomalies:** robust z-score against the same week last year, with baseline and "
            "absolute-gap guards.\n"
            "- **Forecast:** direct multi-step panel, Ridge and gradient boosting on log1p revenue, "
            "expanding-origin selection, forecast bounded to 0.4-2.5x the same week last year."
        )

    with right:
        st.markdown("##### Headline forecast numbers")
        test = forecast["test"]
        st.markdown(
            f"- Model: **{forecast['selected_model'].replace('_', ' ')}**\n"
            f"- Hold-out RMSE **{fmt_money(test['rmse'])}**, MAE **{fmt_money(test['mae'])}**\n"
            f"- MAPE **{test['mape']:.1f}%**, MASE **{test['mase']:.2f}**, R² **{test['r2']:.2f}**\n"
            f"- Improvement over seasonal naive: **{forecast['improvement_vs_naive_pct']:.1f}%**\n"
            f"- Mean bias **{test['bias']:+,.0f}** per week: the model is systematically low"
        )
        st.markdown("##### Known limitations")
        st.markdown(
            "- The weekday mix in the published extract is distorted (Wednesday is 4% of lines).\n"
            "- Single large orders dominate weekly variance; a point forecast cannot capture them.\n"
            "- The evaluation quarter set a record, so R² is negative and intervals under-cover.\n"
            "- No promotion, inventory or marketing calendar is available."
        )
        st.markdown("##### Links")
        st.markdown(
            f"- [Repository]({REPO_URL})\n"
            "- `reports/REPORT.md` for the long-form write-up\n"
            "- `reports/MODEL_CARD.md` for the model's scope and failure modes"
        )

    st.markdown(
        '<div class="callout">Built with pandas, scikit-learn, matplotlib and Streamlit. '
        "The dashboard reads only the committed feed in <code>data/dashboard</code>, so it runs "
        "without downloading the raw data. Rerun the pipeline and every number here changes with it."
        "</div>",
        unsafe_allow_html=True,
    )
